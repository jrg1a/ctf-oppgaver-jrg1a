"""
LØSNING — RE-03: Mini-VM

Analyse i Ghidra avslører:
  1. En BYTECODE[]-array med VM-instruksjoner
  2. En vm_run()-funksjon med en switch-case over opkoder
  3. Instruksjonssettet: PUSH, LOAD, XOR, ADD, CMP, AND, HALT_OK, HALT_FAIL, JZ

Mønsteret i bytekoden er repetitivt:
  02 <idx> 01 <byte> 03 09 01 08
  = LOAD idx, PUSH byte, XOR, JZ+1, HALT_FAIL

XOR av input[i] med <byte> må gi 0 → input[i] == <byte>

Ekstraher alle <byte>-verdier fra bytekoden:
"""

# Bytekoden fra binæren (reversert i Ghidra)
BYTECODE = bytes([
    0x02, 0x00, 0x01, 0x76, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x01, 0x01, 0x6D, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x02, 0x01, 0x5F, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x03, 0x01, 0x6D, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x04, 0x01, 0x34, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x05, 0x01, 0x67, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x06, 0x01, 0x31, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x07, 0x01, 0x63, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x08, 0x01, 0x5F, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x09, 0x01, 0x6B, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x0A, 0x01, 0x33, 0x03, 0x09, 0x01, 0x08,
    0x02, 0x0B, 0x01, 0x79, 0x03, 0x09, 0x01, 0x08,
    0x07,
])

# Ekstraher forventede tegn: LOAD(02) <idx>, PUSH(01) <byte>
nokkel = []
i = 0
while i < len(BYTECODE):
    if BYTECODE[i] == 0x02:       # LOAD
        i += 2
        if BYTECODE[i] == 0x01:   # PUSH
            nokkel.append(chr(BYTECODE[i + 1]))
            i += 2
    else:
        i += 1

nokkel_str = "".join(nokkel)
print(f"Nøkkel: {nokkel_str}")
print(f"Flagg:  CTF{{{nokkel_str}}}")
